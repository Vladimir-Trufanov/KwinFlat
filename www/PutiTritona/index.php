<p><img src="PutiTritona2.jpg" /></p>
<h4 id="роза-пик-2320-по-трассе-тритон-до-отметки-роза-1600---что-вас-ждёт">Роза пик 2320 по трассе Тритон до отметки Роза 1600 - что вас ждёт</h4>
<p>Тропа «Путь тритона» проходит по живописным южным склонам курорта «Роза Хутор», где летом раскрываются яркие краски альпийских лугов, пастбища, цветущие рододендроны и панорамные виды на горную Абхазию. Тропа пролегает через центральную часть южного кластера, пересекает канатные дороги и горнолыжные трассы. В верхней зоне она проходит по альпийскому поясу, а ниже уходит в вековой пихтовый лес, где скрыто горное озеро с краснокнижными тритонами.</p>
<p>«Путь тритона» служит альтернативным способом добраться до Природного парка водопадов «Менделиха» наряду с тропой «Явор». Вернуться на Роза Пик можно по канатной дороге «Эдельвейс», сохранив силы и время.</p>
<p>Маршрут начинается на перевале Красивый (2210 м). Чтобы добраться до старта, нужно подняться на канатных дорогах («Олимпия», «Заповедный лес» или «Кавказский экспресс») до смотровой площадки «Роза Пик» (2320 м), а затем пройти по короткой тропе «Горизонт» до перевала.</p>
<p>Далее тропа спускается по южному склону хребта. По пути вы увидите:</p>
<ul>
<li><p>Альпийские луга — в верхней части маршрута. Летом они усыпаны цветами, а с некоторых точек открываются панорамные виды, в том числе на горную Абхазию.</p></li>
<li><p>Пастбища.</p></li>
<li><p>Вековой пихтовый лес — ниже, где воздух наполнен смолистым ароматом.</p></li>
<li><p>Горное озеро — именно из-за него тропа получила название. В нём обитают краснокнижные тритоны. Озеро довольно небольшое, но очень уединённое.</p></li>
<li><p>В нижней части маршрут пересекается с тропой «Явор», и вместе они ведут к Природному парку водопадов «Менделиха».</p></li>
</ul>
