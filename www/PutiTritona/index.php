<h2 id="путь-тритона">Путь тритона</h2>
<p>Тропа «Путь тритона» — это пеший маршрут на курорте «Роза Хутор».</p>
<h4 id="как-добраться">Как добраться</h4>
<p>Подняться на канатных дорогах Олимпия, Заповедный лес и Кавказский экспресс до Роза Пик 2320м. Далее следуя указателям, через короткую тропу «Горизонт» на перекрестке можно начать спуск по тропе «Путь тритона» к водопадам Менделиха.</p>
