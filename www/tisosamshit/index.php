<p><strong><em>Однако, по словам заместителя директора по экологическому просвещению Кавказского заповедника Ольги Пеговой, исчезновение самшита привело к изменениям в экосистеме рощи: стало светлее, изменилась влажность, появились новые насекомые и птицы.</em></strong></p>
