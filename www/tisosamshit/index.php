<h4 id="какие-редкие-виды-растений-можно-найти-в-тисо-самшитовой-роще">Какие редкие виды растений можно найти в тисо-самшитовой роще?</h4>
<p>Тисо-самшитовая роща в Сочи — уникальный реликтовый лес, где сохранились растения доледникового периода. Среди редких видов, которые можно здесь встретить, особенно выделяются тис ягодный, самшит колхидский и зимовник.</p>
<figure>
<img src="tis1.png" alt="Тис ягодный (Taxus baccata)" /><figcaption>Тис ягодный (Taxus baccata)</figcaption>
</figure>
<p>Вечнозелёное хвойное дерево, которое может достигать возраста 1500–2000 лет, а отдельные экземпляры — до 4000 лет. Высота дерева — до 35 метров, диаметр ствола — до 1,5 метра. Крона часто многовершинная, хвоя плоская, остроконечная, длиной до 2,7 см. Вместо шишек после пыления формируется одиночное семя с мясистым, ярко-малиновым валиком — шишкоягода.</p>
<p>Древесина тиса прочная, твёрдая, упругая, не гниёт, ценится за красоту и бактерицидные свойства. Все части растения, за исключением ариллуса (мясистого валика), ядовиты.</p>
<p>Тис ягодный занесён в Красные книги России и ряда её регионов, таких как Краснодарский и Ставропольский края, а также республик: Адыгея, Дагестан, Южная Осетия, Крым, Кабардино-Балкария, Ингушетия, Карачаево-Черкесия, Северная Осетия-Алания, Армения, Азербайджан.</p>
<figure>
<img src="samshit.jpg" alt="Самшит колхидский (Buxus colchica)" /><figcaption>Самшит колхидский (Buxus colchica)</figcaption>
</figure>
<p>Вечнозелёный кустарник или небольшое дерево высотой 2–12 метров. Листья голые, кожистые, супротивные, овально-ланцетные, длиной 1–3 см. Верхняя поверхность листа тёмно-зелёная, нижняя — светло-зелёная. Цветки жёлто-зелёные, в пазушных головчатых соцветиях.</p>
<p>Самшит растёт крайне медленно, но может жить до 500–600 лет. Его древесина настолько плотная, что тонет в воде.</p>
<p>Вид находится в опасности из-за сокращения мест обитания. Он включён в Красную книгу России, а также в Красные книги Грузии, Азербайджанской Республики, Республики Адыгеи и Краснодарского края.</p>
<p>В 2012 году при подготовке к Олимпийским играм в Сочи вместе с посадочным материалом самшита вечнозелёного из Италии был завезён опасный инвазионный вредитель — самшитовая огнёвка. Гусеницы стали массово уничтожать самшит в роще. К 2016 году вид оказался практически уничтожен в этом месте. Сейчас ведутся восстановительные посадки в горных районах.</p>
<figure>
<img src="morozn_3.jpg" alt="Зимовник" /><figcaption>Зимовник</figcaption>
</figure>
<p>Редкое реликтовое растение, которое появилось на Земле ещё во времена мамонтов. Цветёт зимой, когда большинство растений уже сбросили листву. Его зелёные листья не увядают даже в мороз, а крупные светло-зелёные цветы словно светятся в сумраке леса.</p>
<p>Зимовник занесён в Красные книги Краснодарского края и Карачаево-Черкесии. Собирать это растение запрещено, за его уничтожение предусмотрены штрафы, а в случае значительного ущерба природе — уголовная ответственность.</p>
<p><strong><em>Другие редкие растения рощи</em></strong></p>
<p>В Тисо-самшитовой роще также можно встретить:</p>
<p><strong><em>Клекачку колхидскую</em></strong> — кустарник, который входит в список редких видов, охраняемых на федеральном уровне.</p>
<figure>
<img src="zzin681q5505227bny58xhfbi1qjo64u.png" alt="Клекачка колхидская" /><figcaption>Клекачка колхидская</figcaption>
</figure>
<p><strong><em>Иглицу колхидскую</em></strong> — многолетний полукустарник, занесённый в Красную книгу. Это представитель подлеска влажных, смешанных и лиственных лесов колхидского типа. Растет группами в тенистых ущельях, в самшитниках.</p>
<p>Иглицы (Ruscus) — род растений, входящий в семейство Спаржевые (Asparagaceae). Это вечнозеленые многолетние травянистые растения, а по другой версии - полукустарнички, произрастающие в нижнем ярусе леса.</p>
<p>Для существования в тени кустарников и деревьев, в условиях пониженного солнечного освещения у них появились необычные эволюционные изменения: листья редуцировались до едва заметных полупрозрачных чешуй, а стебли видоизменились в <strong><em>филлокладии</em></strong> - боковые побеги, выполняющие функцию листьев, но таковыми не являющиеся. Филлокладии позволяют растению сохранять воду, испаряя меньше влаги, чем обычные листья, продолжать процесс фотосинтеза, который обеспечивает питание, на них развиваются цветки и плоды.</p>
<p>Краснокнижный статус иглиц не спасает от незаконного сбора для использование во флористике в составлении букетов. Ее не выращивают, а хищнически собирают на природной территории, хотя за сбор краснокнижных растений предусмотрена административная и уголовная ответственность. О задержании сборщиков иглицы сообщали на сайте в материалах.</p>
<p>Сочинский национальный парк делает все возможное, чтобы сохранить растение на особо охраняемой природной территории: здесь не косят, не вытаптывают, не рубят, охраняют. Но иглица растет не в вольере, а в лесу, открытом для всех. Ущерб, нанесенный природе сбором иглицы, оценивается в миллионы рублей, а выгода сборщиков гораздо скромнее! Но ни штрафы, ни протоколы не остановят сбор, пока есть спрос.</p>
<p><strong><em>Поэтому самое главное, что может сделать каждый из нас - не покупать букеты с иглицей.</em></strong></p>
<figure>
<img src="153052742712594294.jpg" alt="Иглица колхидская" /><figcaption>Иглица колхидская</figcaption>
</figure>
<p><strong><em>Рододендрон понтийский</em></strong> — вечнозелёный кустарник с крупными цветами.</p>
<p><strong><em>Падуб колхидский</em></strong> — дерево с блестящими листьями и красными ягодами.</p>
<figure>
<img src="medium.jpeg" alt="Падуб колхидский" /><figcaption>Падуб колхидский</figcaption>
