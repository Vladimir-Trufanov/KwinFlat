<h2 id="тисо-самшитовая-роща"><a href="https://yandex.ru/alice/chat/5af936aa-87bc-4514-b6c1-0a94d0d2f19e/?reqid=1789105118625154-5454628111255357359-balancer-l7leveler-kubr-yp-vla-79-BAL&amp;theme=serp&amp;source_query=Тисо-самшитовая+роща&amp;utm_source=yandex&amp;utm_medium=interface&amp;utm_campaign=serp_alice_requery">Тисо-самшитовая роща</a></h2>
<p>Тисо-самшитовая роща — это уникальный реликтовый лес на восточном склоне горы Ахун в Хостинском районе Сочи, часть Кавказского государственного природного биосферного заповедника имени Х. Г. Шапошникова. Роща представляет собой своеобразный живой музей, где сохранились растения доледникового периода.</p>
<h4 id="история-и-статус">История и статус</h4>
<p>Статус заповедной территории роща получила в 1931 году. В 1950 году она была включена в состав Кавказского заповедника, а также является частью Сочинского национального парка.</p>
<h4 id="флора-и-фауна">Флора и фауна</h4>
<p>Главная ценность рощи — её древняя флора. Здесь растут растения, которые существовали ещё во времена динозавров.</p>
<p>Основные представители флоры:</p>
<p>Тис ягодный — вечнозелёное хвойное дерево, которое может жить 1500–2000 лет. Отдельные экземпляры достигают высоты до 30 метров. Его древесина отличается прочностью и красноватым оттенком, за что тис называют «красным деревом».</p>
<p>Самшит колхидский — вечнозелёный кустарник или небольшое дерево с плотной кроной. Его древесина настолько тяжёлая, что тонет в воде, за что самшит называют «железным деревом».</p>
<p>Помимо тиса и самшита, в роще растут бук, граб, липа, падуб, лавровишня, иглица и другие растения. Многие из них занесены в Красную книгу. Животный мир менее заметен: чаще всего можно увидеть ящериц, ежей и птиц.</p>
<h4 id="маршруты-для-прогулок">Маршруты для прогулок</h4>
<p>В роще оборудовано три туристических маршрута:</p>
<p><strong><em>«Малое кольцо»</em></strong> (1,6 км) — короткий и несложный маршрут, подходящий для первого знакомства с рощей. Он проходит мимо каменного лабиринта, Белых скал и тиса-великана.</p>
<p><strong><em>«Большое кольцо»</em></strong> (5 км) — более насыщенный маршрут, который занимает 3–6 часов. Он включает посещение Буковой поляны, древней крепости, реки Хоста, родника и пещеры.</p>
<p><strong><em>«В глубь веков»</em></strong> (800 м) — линейный маршрут, ведущий от древней крепости к каньону «Чёртовы ворота». На значительной части пути тропа проходит по металлическому настилу над пропастью.</p>
