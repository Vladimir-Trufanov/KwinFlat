<h3 id="ореховский-водопад">Ореховский водопад</h3>
<p>Ореховский водопад — один из самых живописных уголков природы в окрестностях Сочи. Двухкаскадный поток, низвергающийся с высоты, создаёт впечатляющую картину. Нижняя ступень, высотой около 27,5 метров, особенно притягательна для туристов. У её подножия бурлящие струи образуют небольшое озеро с водой удивительной чистоты, словно сотканной из горного хрусталя.</p>
<p>Водопад окружен густым реликтовым лесом, где среди древних деревьев встречаются могучие грецкие орехи. Однако своё название он получил не из-за них, а от близлежащего хутора Ореховка.</p>
<p>Особая прелесть Ореховского водопада — в его переменчивой красоте, доступной в любое время года. Весной и летом он шумен и полноводен, осенью и зимой — становится более сдержанным, но от этого лишь обретает утончённое очарование.</p>
<h3 id="водопады-сванидзе">Водопады Сванидзе</h3>
<p>Водопады Сванидзе — это каскад небольших водопадов на ручье Сванидзе, притоке реки Агва. Водопады Сванидзе находятся между Ореховским водопадом и водопадом Ажек. Это место отличается своей уединённостью и дикой природой, так как здесь нет массовых экскурсий и туристической инфраструктуры. Водопады разбросаны на протяжении 3,5 километров ручья, их высота варьируется от 0,5 до 10 метров. Особую атмосферу создают небольшие метровые водопады, которых на некоторых участках насчитывается более семи на 100 метров.</p>
<p>Ручей Сванидзе окружён густым лесом, где растут мхи, самшит, лианы и редкие растения из Красной книги. В некоторых местах под водопадами образовались природные каменные ванны, где можно освежиться в жаркий день. Это место также известно своей богатой фауной: здесь можно встретить чёрного аиста и других лесных обитателей.</p>
